def get_region(name: str) -> tuple[float, float, float, float]:
    key = name.strip().lower().replace(" ", "_")
    if key not in REGIONS:
        available = ", ".join(sorted(REGIONS))
        raise KeyError(f"Unknown region '{name}'. Available: {available}")
    return REGIONS[key]
